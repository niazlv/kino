package provider

import (
	"time"

	"github.com/niazleushkin/kino/internal/domain/kernel"
)

// Title — тайтл, каким его видит ПРОВАЙДЕР. Ещё не канонический: у него нет
// нашего TitleID, потому что склейка одного произведения из разных площадок
// происходит слоем выше и принадлежит платформе, а не источнику.
type Title struct {
	Ref  kernel.ProviderRef
	Kind string // "movie" | "series"

	// Внешние идентификаторы уже в КАНОНИЧЕСКОЙ форме: адаптер обязан
	// привести их сам (kinopub отдаёт imdb голым числом). Иначе матчинг
	// молча не находит совпадений.
	IMDB      string // "tt0898266"
	Kinopoisk string
	// MAL — номер на MyAnimeList (он же у Shikimori). У аниме это самый
	// надёжный ключ склейки между аниме-площадками, но он СЕЗОННЫЙ: у
	// каждого сезона свой номер.
	MAL string

	Title string
	// Original и AltTitles — оригинальное и прочие названия. Нужны склейке:
	// русские названия аниме у площадок расходятся, ромадзи — реже.
	Original  string
	AltTitles []string
	// SeasonNo > 0 — элемент площадки описывает не всё произведение, а один
	// его сезон. Так устроены аниме-площадки: «2 сезон» — отдельная
	// страница. Ноль — элемент покрывает произведение целиком со своей
	// нумерацией сезонов, как у kinopub.
	SeasonNo  int
	Year      int
	Plot      string
	Genres    []string
	// Countries — страны производства, как их пишет площадка: «Корея
	// Южная», «США». Жанра «дорама» у площадок нет, и вид корейского
	// произведения без стран не определить.
	Countries []string
	Poster    string
	Finished  bool
	UpdatedAt time.Time
	// CreatedAt — когда тайтл появился У ПЛОЩАДКИ. «Новинки» строятся по
	// нему, а не по порядку нашего обхода: тот зависит от нас и к
	// содержимому отношения не имеет.
	CreatedAt time.Time
	// Popularity — сколько примерно людей знают произведение. Шкала общая
	// для всех площадок — число людей, а не баллы или просмотры самой
	// площадки, — поэтому числа разных площадок сравнимы. Ноль — площадка
	// не знает. Поиск ставит популярное вперёд среди одинаково подходящих.
	Popularity int64
}

// Episode — серия у провайдера.
type Episode struct {
	Ref         kernel.ProviderRef
	SeasonNo    int
	EpisodeNo   int
	Title       string
	DurationSec int
	// DurationApprox — длительность не этой серии, а оценка: площадка знает
	// одну длину на весь тайтл («23 мин.») и раздаёт её всем сериям. Такая
	// длина годится, пока точной нет ни у кого, но не заменяет точную —
	// спешл на семь минут остался бы «23-минутным».
	DurationApprox bool
	// Thumbnail — кадр из серии; витрина показывает его вместо голого номера.
	Thumbnail string
}

// WatchRecord — позиция просмотра, накопленная НА СТОРОНЕ ПЛОЩАДКИ.
//
// Существует ради однократного переноса: семья смотрит через площадку
// годами, и обнулить это при переезде значит вернуть всех в старое
// приложение в первый же вечер. Обратной записи нет и не будет — раздельное
// состояние у каждого и есть причина существования платформы.
type WatchRecord struct {
	Ref         kernel.ProviderRef
	SeasonNo    int
	EpisodeNo   int
	PositionSec int
	DurationSec int
	Completed   bool
	// WatchedAt — когда серию смотрели у площадки; ноль — неизвестно.
	// Без неё все перенесённые позиции получали дату переноса, и «История»
	// с «Продолжить смотреть» шли в случайном порядке.
	WatchedAt time.Time
}

// BookmarkFolder — папка закладок на стороне площадки. У семейной подписки
// это единственное, что у каждого своё: «Данис», «Нияз». Тоже только ради
// однократного переноса.
type BookmarkFolder struct {
	ID    string
	Title string
	Count int
}

// ExternalIDs — внешние номера произведения, по которым площадку можно
// спросить напрямую. Форма та же, что у Title: imdb с «tt», Кинопоиск —
// голым числом.
type ExternalIDs struct {
	IMDB      string
	Kinopoisk string

	// Название, оригинал, год и вид тайтла, о котором спрашивают. Площадкам
	// без номеров (Filmix) — искать по названию: находку они отдают, только
	// если она совпала целиком, и приписывают ей номера отсюда.
	Title    string
	Original string
	Year     int
	Kind     string // movie | series
}

// Empty — спрашивать нечем.
func (x ExternalIDs) Empty() bool { return x.IMDB == "" && x.Kinopoisk == "" }
