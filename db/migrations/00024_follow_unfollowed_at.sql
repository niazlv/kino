-- +goose Up
-- «Слежу» теперь ставится и само: досмотрел серию идущего сериала или
-- отметил её просмотренной — значит, ждёшь следующую. Снятое руками
-- автоматика возвращать не вправе, а по одному following=false не понять,
-- сняли его или не ставили вовсе: строку отметок заводят и «Буду смотреть»,
-- и выбор дорожки в плеере. unfollowed_at — когда человек сам снял
-- слежение; пока оно стоит, само «Слежу» не ставится. Явное «Слежу»
-- его стирает.
--
-- Номер 00024: 00023 занят невлитой работой со странами производства;
-- migrate применяет пропущенные номера (allow missing).
ALTER TABLE user_titles ADD COLUMN unfollowed_at TIMESTAMPTZ;

-- Строку, где не отмечено ничего и нет выбора дорожек, оставляет только
-- кнопка отметок: это след снятого «Слежу» (или «Буду смотреть»). Такие
-- считаются снятыми руками: так человек вычищает свой список. Строки с
-- выбором дорожки пишет плеер: там «Слежу» никто не ставил и не снимал.
UPDATE user_titles SET unfollowed_at = updated_at
WHERE NOT following AND NOT watchlist
  AND audio_pref IS NULL AND text_pref IS NULL AND source_pref IS NULL;

