-- +goose Up
-- Поиск по ключам названий, а не только по витринному названию.
--
-- Витринное пишется как у площадки: «Принцесса-медуза / Kuragehime». Человек
-- набирает «принцесса медуза» — через пробел, — и подстрока не совпадает.
-- Ключи названий сведены к одной форме (регистр, «ё», знаки) и включают
-- альтернативные названия площадок; подстрочный поиск по ним держит
-- триграммный индекс.
CREATE INDEX title_names_name_key_trgm ON title_names USING gin (name_key gin_trgm_ops);

-- +goose Down
DROP INDEX IF EXISTS title_names_name_key_trgm;
